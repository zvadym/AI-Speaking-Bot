CREATE TABLE llm_call_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT NOW(),
  decision_id text,
  chat_id bigint,
  bot_key text NOT NULL,
  route text,
  operation text NOT NULL,
  model text NOT NULL,
  reasoning_effort text,
  duration_ms integer NOT NULL,
  success boolean NOT NULL,
  error_code text,
  input_tokens bigint,
  cached_input_tokens bigint,
  output_tokens bigint,
  reasoning_tokens bigint,
  total_tokens bigint,
  CONSTRAINT llm_call_events_duration_check CHECK (duration_ms >= 0),
  CONSTRAINT llm_call_events_token_counts_check CHECK (
    COALESCE(input_tokens, 0) >= 0 AND
    COALESCE(cached_input_tokens, 0) >= 0 AND
    COALESCE(output_tokens, 0) >= 0 AND
    COALESCE(reasoning_tokens, 0) >= 0 AND
    COALESCE(total_tokens, 0) >= 0
  ),
  CONSTRAINT llm_call_events_error_state_check CHECK (
    (success = true AND error_code IS NULL) OR
    (success = false AND error_code IS NOT NULL)
  )
);

CREATE INDEX idx_llm_call_events_occurred
  ON llm_call_events (occurred_at DESC);

CREATE INDEX idx_llm_call_events_bot_operation_occurred
  ON llm_call_events (bot_key, operation, occurred_at DESC);

CREATE INDEX idx_llm_call_events_decision
  ON llm_call_events (decision_id)
  WHERE decision_id IS NOT NULL;

