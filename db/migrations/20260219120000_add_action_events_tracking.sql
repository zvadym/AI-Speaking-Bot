CREATE TABLE IF NOT EXISTS public.action_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id bigint NOT NULL,
  bot_key text,
  action_type text NOT NULL,
  source text NOT NULL DEFAULT 'unknown',
  idempotency_key text UNIQUE,
  properties jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT action_events_action_type_check CHECK (
    action_type IN (
      'start',
      'profile_set_level',
      'first_voice_sent',
      'first_answer_delivered',
      'paywall_shown',
      'purchase_success',
      'day1_return'
    )
  )
);

CREATE INDEX IF NOT EXISTS idx_action_events_occurred
  ON public.action_events (occurred_at DESC);

CREATE INDEX IF NOT EXISTS idx_action_events_action_occurred
  ON public.action_events (action_type, occurred_at DESC);

CREATE INDEX IF NOT EXISTS idx_action_events_bot_action_occurred
  ON public.action_events (bot_key, action_type, occurred_at DESC);

CREATE INDEX IF NOT EXISTS idx_action_events_chat_action_occurred
  ON public.action_events (chat_id, action_type, occurred_at DESC);

CREATE OR REPLACE FUNCTION public.log_first_voice_sent_from_usage_event()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.direction <> 'in' THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.action_events (
    chat_id,
    bot_key,
    action_type,
    source,
    idempotency_key,
    occurred_at
  )
  VALUES (
    NEW.chat_id,
    NEW.bot_key,
    'first_voice_sent',
    'db_trigger',
    'first_voice_sent:' || NEW.chat_id::text || ':' || COALESCE(NEW.bot_key, ''),
    NEW.occurred_at
  )
  ON CONFLICT (idempotency_key) DO NOTHING;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.log_first_answer_delivered_from_message()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.role <> 'assistant' THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.action_events (
    chat_id,
    bot_key,
    action_type,
    source,
    idempotency_key,
    occurred_at
  )
  VALUES (
    NEW.chat_id,
    NEW.bot_key,
    'first_answer_delivered',
    'db_trigger',
    'first_answer_delivered:' || NEW.chat_id::text || ':' || COALESCE(NEW.bot_key, ''),
    NEW.created_at
  )
  ON CONFLICT (idempotency_key) DO NOTHING;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.log_day1_return_from_user_bot()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.last_seen_at < (NEW.first_seen_at + INTERVAL '1 day') THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.action_events (
    chat_id,
    bot_key,
    action_type,
    source,
    idempotency_key,
    occurred_at,
    properties
  )
  VALUES (
    NEW.chat_id,
    NEW.bot_key,
    'day1_return',
    'db_trigger',
    'day1_return:' || NEW.chat_id::text || ':' || COALESCE(NEW.bot_key, ''),
    NEW.last_seen_at,
    jsonb_build_object(
      'first_seen_at', NEW.first_seen_at,
      'last_seen_at', NEW.last_seen_at
    )
  )
  ON CONFLICT (idempotency_key) DO NOTHING;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_action_first_voice_sent ON public.voice_usage_events;
CREATE TRIGGER trg_action_first_voice_sent
AFTER INSERT ON public.voice_usage_events
FOR EACH ROW
EXECUTE FUNCTION public.log_first_voice_sent_from_usage_event();

DROP TRIGGER IF EXISTS trg_action_first_answer_delivered ON public.messages;
CREATE TRIGGER trg_action_first_answer_delivered
AFTER INSERT ON public.messages
FOR EACH ROW
EXECUTE FUNCTION public.log_first_answer_delivered_from_message();

DROP TRIGGER IF EXISTS trg_action_day1_return ON public.user_bots;
CREATE TRIGGER trg_action_day1_return
AFTER INSERT OR UPDATE OF last_seen_at ON public.user_bots
FOR EACH ROW
EXECUTE FUNCTION public.log_day1_return_from_user_bot();

