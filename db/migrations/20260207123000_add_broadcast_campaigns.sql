CREATE TABLE IF NOT EXISTS public.broadcast_campaigns (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text NOT NULL DEFAULT 'queued',
  filters jsonb NOT NULL DEFAULT '{}'::jsonb,
  message_text text NOT NULL,
  total_recipients integer NOT NULL DEFAULT 0,
  sent_count integer NOT NULL DEFAULT 0,
  failed_count integer NOT NULL DEFAULT 0,
  created_by text,
  error_text text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  started_at timestamptz,
  finished_at timestamptz,
  CONSTRAINT broadcast_campaigns_status_check CHECK (
    status IN ('queued', 'sending', 'completed', 'failed')
  )
);

CREATE INDEX IF NOT EXISTS idx_broadcast_campaigns_status_created_at
  ON public.broadcast_campaigns (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.broadcast_recipients (
  campaign_id bigint NOT NULL REFERENCES public.broadcast_campaigns(id) ON DELETE CASCADE,
  chat_id bigint NOT NULL,
  username text,
  first_name text,
  status text NOT NULL DEFAULT 'pending',
  attempts integer NOT NULL DEFAULT 0,
  last_error text,
  sent_at timestamptz,
  telegram_message_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT broadcast_recipients_pkey PRIMARY KEY (campaign_id, chat_id),
  CONSTRAINT broadcast_recipients_status_check CHECK (
    status IN ('pending', 'sent', 'failed')
  )
);

CREATE INDEX IF NOT EXISTS idx_broadcast_recipients_campaign_status
  ON public.broadcast_recipients (campaign_id, status, updated_at DESC);

CREATE INDEX IF NOT EXISTS idx_broadcast_recipients_chat_id
  ON public.broadcast_recipients (chat_id);

