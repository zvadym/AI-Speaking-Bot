CREATE TABLE public.bot_update_effects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  decision_id text NOT NULL,
  step_key text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  result_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bot_update_effects_execution_step_key UNIQUE (decision_id, step_key),
  CONSTRAINT bot_update_effects_execution_fkey
    FOREIGN KEY (decision_id)
    REFERENCES public.bot_update_executions(decision_id)
    ON DELETE CASCADE,
  CONSTRAINT bot_update_effects_status_check CHECK (
    status = ANY (ARRAY['pending'::text, 'completed'::text])
  ),
  CONSTRAINT bot_update_effects_step_key_length_check CHECK (
    char_length(step_key) BETWEEN 1 AND 96
  ),
  CONSTRAINT bot_update_effects_result_object_check CHECK (
    result_json IS NULL OR jsonb_typeof(result_json) = 'object'
  )
);

CREATE INDEX bot_update_effects_status_updated_idx
  ON public.bot_update_effects (status, updated_at);

