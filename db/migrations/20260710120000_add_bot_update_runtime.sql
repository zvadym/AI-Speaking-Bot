CREATE TABLE public.bot_update_executions (
  decision_id text PRIMARY KEY,
  bot_key text NOT NULL,
  update_id bigint NOT NULL,
  contract_version integer NOT NULL,
  route text NOT NULL,
  handler_version integer NOT NULL,
  status text NOT NULL DEFAULT 'running',
  attempts integer NOT NULL DEFAULT 1,
  current_job_id uuid NOT NULL,
  lease_expires_at timestamptz NOT NULL,
  terminal_error_code text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  started_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  CONSTRAINT bot_update_executions_bot_update_key UNIQUE (bot_key, update_id),
  CONSTRAINT bot_update_executions_contract_version_check CHECK (contract_version = 1),
  CONSTRAINT bot_update_executions_handler_version_check CHECK (handler_version > 0),
  CONSTRAINT bot_update_executions_attempts_check CHECK (attempts > 0),
  CONSTRAINT bot_update_executions_status_check CHECK (
    status = ANY (ARRAY[
      'running'::text,
      'succeeded'::text,
      'retryable_failed'::text,
      'permanent_failed'::text
    ])
  ),
  CONSTRAINT bot_update_executions_decision_id_length_check CHECK (char_length(decision_id) BETWEEN 1 AND 128),
  CONSTRAINT bot_update_executions_bot_key_length_check CHECK (char_length(bot_key) BETWEEN 1 AND 32),
  CONSTRAINT bot_update_executions_route_length_check CHECK (char_length(route) BETWEEN 1 AND 64),
  CONSTRAINT bot_update_executions_error_length_check CHECK (
    terminal_error_code IS NULL OR char_length(terminal_error_code) BETWEEN 1 AND 128
  )
);

CREATE INDEX bot_update_executions_status_lease_idx
  ON public.bot_update_executions (status, lease_expires_at, updated_at);

CREATE TABLE public.bot_update_deliveries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  decision_id text NOT NULL,
  step_key text NOT NULL,
  telegram_method text NOT NULL,
  telegram_message_id bigint,
  status text NOT NULL DEFAULT 'pending',
  attempts integer NOT NULL DEFAULT 0,
  error_code text,
  error_detail text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bot_update_deliveries_execution_step_key UNIQUE (decision_id, step_key),
  CONSTRAINT bot_update_deliveries_execution_fkey
    FOREIGN KEY (decision_id)
    REFERENCES public.bot_update_executions(decision_id)
    ON DELETE CASCADE,
  CONSTRAINT bot_update_deliveries_status_check CHECK (
    status = ANY (ARRAY[
      'pending'::text,
      'delivered'::text,
      'failed'::text,
      'unknown'::text
    ])
  ),
  CONSTRAINT bot_update_deliveries_attempts_check CHECK (attempts >= 0),
  CONSTRAINT bot_update_deliveries_step_key_length_check CHECK (char_length(step_key) BETWEEN 1 AND 96),
  CONSTRAINT bot_update_deliveries_method_length_check CHECK (char_length(telegram_method) BETWEEN 1 AND 64),
  CONSTRAINT bot_update_deliveries_error_code_length_check CHECK (
    error_code IS NULL OR char_length(error_code) BETWEEN 1 AND 128
  ),
  CONSTRAINT bot_update_deliveries_error_detail_length_check CHECK (
    error_detail IS NULL OR char_length(error_detail) BETWEEN 1 AND 500
  )
);

CREATE INDEX bot_update_deliveries_status_updated_idx
