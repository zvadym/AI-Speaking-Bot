CREATE TABLE IF NOT EXISTS public.scheduled_task_dispatches (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  task_type text NOT NULL,
  bot_key text NOT NULL,
  chat_id bigint NOT NULL,
  schedule_key text NOT NULL,
  status text NOT NULL DEFAULT 'claimed',
  claimed_at timestamp with time zone NOT NULL DEFAULT NOW(),
  claim_expires_at timestamp with time zone,
  attempts integer NOT NULL DEFAULT 0,
  last_error text,
  payload_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  telegram_message_id bigint,
  sent_at timestamp with time zone,
  created_at timestamp with time zone NOT NULL DEFAULT NOW(),
  updated_at timestamp with time zone NOT NULL DEFAULT NOW(),
  CONSTRAINT scheduled_task_dispatches_status_check CHECK (
    status = ANY (ARRAY['claimed'::text, 'sent'::text, 'failed'::text])
  ),
  CONSTRAINT scheduled_task_dispatches_task_scope_key UNIQUE (task_type, bot_key, chat_id, schedule_key),
  CONSTRAINT scheduled_task_dispatches_user_bot_fkey
    FOREIGN KEY (chat_id, bot_key)
    REFERENCES public.user_bots(chat_id, bot_key)
    ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_scheduled_task_dispatches_status_claim_expires
  ON public.scheduled_task_dispatches (status, claim_expires_at, updated_at DESC);

